#!/usr/bin/env bash
# What this host owes `cargo oxide` before a build: the CPU flags of its triple, the one LLVM `llc` the PTX is made with and
# the patched codegen backend.
#   tools/oxide-host.sh                 write .cargo/cuda-oxide.toml for the host triple, then check CUDA_OXIDE_LLC and the backend
#   tools/oxide-host.sh --flags TRIPLE  TRIPLE's host rustflags from .cargo/config.toml, one flag a line
#   tools/oxide-host.sh --llc           the llc check alone
#   tools/oxide-host.sh --backend       the backend check alone
#   tools/oxide-host.sh --self-test
# Exit 0 when the host is ready; 70 names what is missing and nothing is written past it; 64 is a usage error.
#
# The CPU flags. cargo-oxide builds with its own CARGO_ENCODED_RUSTFLAGS, which hides `target.<triple>.rustflags` of
# .cargo/config.toml, and reads one flat `extra-rustflags` list from .cargo/cuda-oxide.toml. That list is the same for
# every triple, and a triple that needs another (znver3 on the box, native on an aarch64 Spark) has no place in the file.
# So the file is generated here, for the triple cargo-oxide builds for (CARGO_BUILD_TARGET, else the host rustc's), from
# the one list .cargo/config.toml carries for it; plain cargo and cargo oxide read the same list. A triple with no list
# is refused: the build would take no CPU flag and say nothing. The file is not tracked (.gitignore) and box.sh's rsync
# removes it on every sync, so the command that runs `cargo oxide` makes it first (tools/box.sh). A caller's RUSTFLAGS
# still lands after it, as cargo-oxide appends them (tools/release/build.sh relies on that).
#
# The llc. cuda-oxide takes CUDA_OXIDE_LLC when it is set, and otherwise the Rust toolchain's own llc, which is a newer
# LLVM than the one bloomery's PTX is checked against. The host's environment file (BLOOMERY_ENV_FILE, ~/bloomery-env.sh)
# names the path; this refuses an unset name, a file that does not run, a banner with no version and a major other than
# WANT_LLVM, each by name, and prints the path and the version line it found. cuda-oxide pairs `opt` with the same
# directory's or a same-major tool by itself.
#
# The backend. The file also names the codegen backend (`backend = <path>`, cargo-oxide's second choice after
# CUDA_OXIDE_BACKEND), and tools/oxide-backend.sh --check refuses by name a backend built without the patch of
# tools/oxide-backend/cuda-rust-1648.patch (that script's header says why), so a build never runs on an unpatched one.
set -euo pipefail

WANT_LLVM=21
ROOT=$(cd "$(dirname "$0")/.." && pwd)

refuse() { # refuse <message>: the one exit for a host that is not ready
  echo "oxide-host: $1" >&2
  exit 70
}

# host_triple: the triple cargo-oxide builds for, the way it picks it (CARGO_BUILD_TARGET, else the host rustc's).
host_triple() {
  if [ -n "${CARGO_BUILD_TARGET:-}" ]; then
    printf '%s\n' "$CARGO_BUILD_TARGET"
    return
  fi
  local host
  host=$(rustc -vV 2>/dev/null | sed -n 's/^host: //p' || true)
  [ -n "$host" ] || refuse "cannot read the host triple from \`rustc -vV\` in $PWD"
  printf '%s\n' "$host"
}

# flags_of TRIPLE: the rustflags of .cargo/config.toml's [target.TRIPLE], one a line.
flags_of() {
  [ -f .cargo/config.toml ] || refuse "no .cargo/config.toml in $PWD: the CPU flags of an oxide build come from its [target.<triple>] rustflags"
  python3 -I - "$1" <<'PY' || exit 70
import sys, tomllib

triple = sys.argv[1]
with open(".cargo/config.toml", "rb") as fh:
    cfg = tomllib.load(fh)
flags = cfg.get("target", {}).get(triple, {}).get("rustflags")
if not isinstance(flags, list) or not flags or not all(isinstance(f, str) for f in flags):
    print(f"oxide-host: .cargo/config.toml has no [target.{triple}] rustflags list: an oxide build for {triple} "
          "would compile its host code with no CPU flag and say nothing. Add the list there (plain cargo reads it "
          "too) or build for a triple that has one", file=sys.stderr)
    sys.exit(1)
print("\n".join(flags))
PY
}

# write_config TRIPLE: .cargo/cuda-oxide.toml for TRIPLE, replaced only when its text differs. A file this script did not
# write is another owner's and is refused, never overwritten.
write_config() {
  local triple=$1 flags backend
  flags=$(flags_of "$triple") || exit 70
  backend=$(bash tools/oxide-backend.sh --path) || exit 70
  python3 -I - "$triple" "$backend" "$flags" <<'PY' || exit 70
import json, os, sys

triple, backend, flags = sys.argv[1], sys.argv[2], sys.argv[3].split("\n")
HEADER = "# Generated by tools/oxide-host.sh"
path = ".cargo/cuda-oxide.toml"
text = (f"{HEADER} (untracked): the host rustflags of {triple} from .cargo/config.toml,\n"
        "# as the one flat list cargo-oxide reads, and the patched backend of tools/oxide-backend.sh.\n"
        "# Edit .cargo/config.toml, not this file.\n"
        f"extra-rustflags = [{', '.join(json.dumps(f) for f in flags)}]\n"
        f"backend = {json.dumps(backend)}\n")
if os.path.exists(path):
    with open(path, encoding="utf-8") as fh:
        old = fh.read()
    if old == text:
        sys.exit(0)
    if not old.startswith(HEADER):
        print(f"oxide-host: {path} was not written by tools/oxide-host.sh: it may hold settings of another owner "
              "(a default arch), and the CPU flags now come from .cargo/config.toml and the backend from "
              "tools/oxide-backend.sh. Remove it, or merge what it sets into the environment", file=sys.stderr)
        sys.exit(1)
# Its own temp name: lanes of a batch prepare the same tree at once, and a shared name lets one rename the
# other's file away.
tmp = f"{path}.{os.getpid()}.tmp"
with open(tmp, "w", encoding="utf-8") as fh:
    fh.write(text)
os.replace(tmp, path)
PY
  printf 'oxide-host: %s host rustflags: %s\n' "$triple" "$(printf '%s' "$flags" | tr '\n' ' ' | sed 's/ $//')" >&2
}

# check_llc: CUDA_OXIDE_LLC names an LLVM WANT_LLVM llc that runs; prints its path and version line.
check_llc() {
  local llc=${CUDA_OXIDE_LLC-} banner rc line major
  [ -n "$llc" ] || refuse "CUDA_OXIDE_LLC is not set: cuda-oxide would use the Rust toolchain's own llc, a newer LLVM than the LLVM $WANT_LLVM bloomery's PTX is made with. Name this host's LLVM $WANT_LLVM llc in its environment file (BLOOMERY_ENV_FILE, ~/bloomery-env.sh)"
  case $llc in
    */*) ;;
    *) llc=$(command -v -- "$llc" 2>/dev/null) || refuse "CUDA_OXIDE_LLC=$CUDA_OXIDE_LLC is a bare name that is on no PATH directory" ;;
  esac
  [ -f "$llc" ] && [ -x "$llc" ] || refuse "CUDA_OXIDE_LLC=$llc is not an executable file"
  banner=$("$llc" --version 2>&1) && rc=0 || rc=$?
  [ "$rc" = 0 ] || refuse "\`$llc --version\` ended $rc: ${banner:0:200}"
  line=$(printf '%s\n' "$banner" | grep -E 'LLVM version [0-9]+\.[0-9]+' | head -n 1 | sed -E 's/^[[:space:]]+//; s/[[:space:]]+$//' || true)
  [ -n "$line" ] || refuse "\`$llc --version\` has no 'LLVM version N.M' line: $(printf '%s' "$banner" | head -n 1 | cut -c1-200)"
  major=$(printf '%s' "$line" | sed -E 's/.*LLVM version ([0-9]+)\..*/\1/')
  [ "$major" = "$WANT_LLVM" ] || refuse "$llc is LLVM $major ($line); bloomery's PTX is made with LLVM $WANT_LLVM. Point CUDA_OXIDE_LLC at an LLVM $WANT_LLVM llc"
  echo "oxide-host: llc $llc: $line" >&2
}

# check_backend: the backend cargo-oxide will use (CUDA_OXIDE_BACKEND, else the one tools/oxide-backend.sh installed) is the
# pin's and carries the patch.
check_backend() {
  bash tools/oxide-backend.sh --check || exit 70
}

self_test() {
  local t fails=0 out rc rev=0123456789abcdef0123456789abcdef01234567 psha
  t=$(mktemp -d "${TMPDIR:-/tmp}/oxide-host.XXXXXX")
  trap 'rm -rf "$t"' RETURN
  mkdir -p "$t/tree/.cargo" "$t/tree/tools" "$t/bin"
  cp "$0" "$t/tree/tools/oxide-host.sh"
  cat > "$t/tree/.cargo/config.toml" <<'EOF'
[target.x86_64-unknown-linux-gnu]
rustflags = ["-C", "target-cpu=znver3", "-C", "target-feature=-sse4a"]

[target.aarch64-unknown-linux-gnu]
rustflags = ["-C", "target-cpu=native"]

[target.riscv64gc-unknown-linux-gnu]
rustflags = []
EOF
  mkdir -p "$t/tree/tools/oxide-backend" "$t/backends/$rev"
  cp "$(dirname "$0")/oxide-backend.sh" "$t/tree/tools/oxide-backend.sh"
  printf '[workspace.dependencies]\ncuda-device = { git = "https://github.com/NVIDIA/cuda-rust.git", rev = "%s" }\n' "$rev" > "$t/tree/Cargo.toml"
  printf -- '--- a/x\n+++ b/x\n@@ -1 +1 @@\n-a\n+b\n' > "$t/tree/tools/oxide-backend/cuda-rust-1648.patch"
  psha=$( (sha256sum "$t/tree/tools/oxide-backend/cuda-rust-1648.patch" 2>/dev/null || shasum -a 256 "$t/tree/tools/oxide-backend/cuda-rust-1648.patch") | cut -d' ' -f1)
  printf 'so\n' > "$t/backends/$rev/librustc_codegen_cuda.so"
  printf '%s\n' "$rev" > "$t/backends/$rev/source-rev.txt"
  printf 'patch-sha256: %s tools/oxide-backend/cuda-rust-1648.patch\n' "$psha" > "$t/backends/$rev/PROVENANCE"
  stub_llc() { # stub_llc FILE MAJOR.MINOR.PATCH [bare]: a script that prints the banner of an llc
    printf '#!/bin/sh\necho "LLVM (http://llvm.org/):"\necho "  LLVM version %s"\necho "  Optimized build."\n' "$2" > "$1"
    chmod +x "$1"
  }
  stub_llc "$t/bin/llc21" 21.1.8
  stub_llc "$t/bin/llc22" 22.1.0
  printf '#!/bin/sh\necho "not an llc"\n' > "$t/bin/llc-nobanner"
  printf '#!/bin/sh\necho "boom" >&2\nexit 3\n' > "$t/bin/llc-fails"
  chmod +x "$t/bin/llc-nobanner" "$t/bin/llc-fails"
  printf '#!/bin/sh\necho "host: aarch64-unknown-linux-gnu"\n' > "$t/bin/rustc"
  chmod +x "$t/bin/rustc"
  # run NAME WANT_RC PATTERN [ENV…] -- ARGS…: the script in the scratch tree; its output must match PATTERN
  run() {
    local name=$1 want=$2 pat=$3
    shift 3
    out=$(cd "$t/tree" && env -u CUDA_OXIDE_LLC -u CUDA_OXIDE_BACKEND -u CARGO_BUILD_TARGET BLOOMERY_OXIDE_BACKENDS="$t/backends" "$@" 2>&1) && rc=0 || rc=$?
    if [ "$rc" = "$want" ] && printf '%s\n' "$out" | grep -Eq -- "$pat"; then
      echo "oxide-host self-test: ok  $name"
    else
      echo "oxide-host self-test: BAD $name: rc $rc (want $want), output: $out"
      fails=$((fails + 1))
    fi
  }
  local before after oh="$t/tree/tools/oxide-host.sh" X=x86_64-unknown-linux-gnu A=aarch64-unknown-linux-gnu
  run 'flags of x86_64' 0 '^-C$' bash "$oh" --flags $X
  [ "$(cd "$t/tree" && bash "$oh" --flags $X | tr '\n' ' ')" = "-C target-cpu=znver3 -C target-feature=-sse4a " ] || { echo "oxide-host self-test: BAD flags of x86_64 are not the config's list"; fails=$((fails + 1)); }
  run 'flags of aarch64' 0 'target-cpu=native' bash "$oh" --flags $A
  run 'a triple with no table is refused by name' 70 "no \[target\.mips-unknown-linux-gnu\] rustflags list" bash "$oh" --flags mips-unknown-linux-gnu
  run 'an empty list is refused' 70 "no \[target\.riscv64gc-unknown-linux-gnu\] rustflags list" bash "$oh" --flags riscv64gc-unknown-linux-gnu
  run 'x86_64 writes its flat list and checks the llc' 0 "oxide-host: llc $t/bin/llc21: LLVM version 21\.1\.8" env CARGO_BUILD_TARGET=$X CUDA_OXIDE_LLC="$t/bin/llc21" bash "$oh"
  if [ "$(cat "$t/tree/.cargo/cuda-oxide.toml")" = "$(printf '# Generated by tools/oxide-host.sh (untracked): the host rustflags of %s from .cargo/config.toml,\n# as the one flat list cargo-oxide reads, and the patched backend of tools/oxide-backend.sh.\n# Edit .cargo/config.toml, not this file.\nextra-rustflags = ["-C", "target-cpu=znver3", "-C", "target-feature=-sse4a"]\nbackend = "%s"' $X "$t/backends/$rev/librustc_codegen_cuda.so")" ]; then
    echo "oxide-host self-test: ok  the file holds the x86_64 list"
  else
    echo "oxide-host self-test: BAD the file does not hold the x86_64 list: $(cat "$t/tree/.cargo/cuda-oxide.toml")"
    fails=$((fails + 1))
  fi
  touch -d '2001-01-01' "$t/tree/.cargo/cuda-oxide.toml" 2>/dev/null || touch -t 200101010000 "$t/tree/.cargo/cuda-oxide.toml"
  before=$(stat -c %Y "$t/tree/.cargo/cuda-oxide.toml" 2>/dev/null || stat -f %m "$t/tree/.cargo/cuda-oxide.toml")
  run 'a second run leaves an equal file alone' 0 'oxide-host: llc' env CARGO_BUILD_TARGET=$X CUDA_OXIDE_LLC="$t/bin/llc21" bash "$oh"
  after=$(stat -c %Y "$t/tree/.cargo/cuda-oxide.toml" 2>/dev/null || stat -f %m "$t/tree/.cargo/cuda-oxide.toml")
  [ "$before" = "$after" ] && echo "oxide-host self-test: ok  an equal file keeps its mtime" || { echo "oxide-host self-test: BAD an equal file was rewritten"; fails=$((fails + 1)); }
  run 'aarch64 replaces the generated file with its own list' 0 'host rustflags: -C target-cpu=native' env CARGO_BUILD_TARGET=$A CUDA_OXIDE_LLC="$t/bin/llc21" bash "$oh"
  grep -q '^extra-rustflags = \["-C", "target-cpu=native"\]$' "$t/tree/.cargo/cuda-oxide.toml" && echo "oxide-host self-test: ok  the file now holds the aarch64 list" || { echo "oxide-host self-test: BAD the aarch64 list is not in the file"; fails=$((fails + 1)); }
  # Two writers of an absent file: each writes its own temp file, so neither renames the other's away. A
  # directory at the old shared name `<file>.tmp` stands for another writer's file there.
  rm -f "$t/tree/.cargo/cuda-oxide.toml"
  mkdir "$t/tree/.cargo/cuda-oxide.toml.tmp"
  run 'another writer at the shared temp name does not stop this one' 0 'host rustflags: -C target-cpu=znver3' env CARGO_BUILD_TARGET=$X CUDA_OXIDE_LLC="$t/bin/llc21" bash "$oh"
  rmdir "$t/tree/.cargo/cuda-oxide.toml.tmp"
  run 'the triple comes from rustc when CARGO_BUILD_TARGET is unset' 0 'aarch64-unknown-linux-gnu host rustflags' env PATH="$t/bin:$PATH" CUDA_OXIDE_LLC="$t/bin/llc21" bash "$oh"
  run 'a triple with no list ends 70 before the llc is read' 70 'no \[target\.mips-unknown-linux-gnu\] rustflags list' env CARGO_BUILD_TARGET=mips-unknown-linux-gnu bash "$oh"
  printf 'backend = "/x/librustc_codegen_cuda.so"\n' > "$t/tree/.cargo/cuda-oxide.toml"
  run 'a file of another owner is refused, not overwritten' 70 'was not written by tools/oxide-host\.sh' env CARGO_BUILD_TARGET=$X CUDA_OXIDE_LLC="$t/bin/llc21" bash "$oh"
  grep -q '^backend = ' "$t/tree/.cargo/cuda-oxide.toml" && echo "oxide-host self-test: ok  the other owner's file is intact" || { echo "oxide-host self-test: BAD the other owner's file was overwritten"; fails=$((fails + 1)); }
  rm -f "$t/tree/.cargo/cuda-oxide.toml"
  run 'an unset CUDA_OXIDE_LLC is refused by name' 70 'CUDA_OXIDE_LLC is not set' bash "$oh" --llc
  run 'a missing llc is refused by name' 70 "CUDA_OXIDE_LLC=$t/bin/none is not an executable file" env CUDA_OXIDE_LLC="$t/bin/none" bash "$oh" --llc
  run 'a bare name on no PATH directory is refused' 70 'bare name that is on no PATH directory' env CUDA_OXIDE_LLC=llc-in-no-dir bash "$oh" --llc
  run 'a bare name on PATH resolves and prints its path' 0 "oxide-host: llc $t/bin/llc21: LLVM version 21\.1\.8" env PATH="$t/bin:$PATH" CUDA_OXIDE_LLC=llc21 bash "$oh" --llc
  run 'another major is refused naming both' 70 'llc22 is LLVM 22 \(LLVM version 22\.1\.0\); bloomery.s PTX is made with LLVM 21' env CUDA_OXIDE_LLC="$t/bin/llc22" bash "$oh" --llc
  run 'a banner with no version is refused' 70 "no 'LLVM version N\.M' line: not an llc" env CUDA_OXIDE_LLC="$t/bin/llc-nobanner" bash "$oh" --llc
  run 'an llc that fails is refused with its rc' 70 'llc-fails --version` ended 3: boom' env CUDA_OXIDE_LLC="$t/bin/llc-fails" bash "$oh" --llc
  run 'the installed backend of the pin passes' 0 "oxide-backend: $t/backends/$rev/librustc_codegen_cuda\.so rev 01234567 patch" bash "$oh" --backend
  printf 'built by cargo-oxide itself\n' > "$t/backends/$rev/PROVENANCE"
  run 'an unpatched backend ends the host check by name' 70 'built without tools/oxide-backend/cuda-rust-1648\.patch' env CARGO_BUILD_TARGET=$X CUDA_OXIDE_LLC="$t/bin/llc21" bash "$oh"
  run 'an unpatched backend named by CUDA_OXIDE_BACKEND is refused too' 70 'built without tools/oxide-backend/cuda-rust-1648\.patch' env CUDA_OXIDE_BACKEND="$t/backends/$rev/librustc_codegen_cuda.so" bash "$oh" --backend
  mkdir -p "$t/other"
  printf 'so\n' > "$t/other/librustc_codegen_cuda.so"
  run 'a backend file elsewhere is held to the same record' 70 "records source rev '', not the pin $rev" env CUDA_OXIDE_BACKEND="$t/other/librustc_codegen_cuda.so" bash "$oh" --backend
  printf 'patch-sha256: %s tools/oxide-backend/cuda-rust-1648.patch\n' "$psha" > "$t/backends/$rev/PROVENANCE"
  run 'the record restored, the host is ready again' 0 'oxide-backend: ' env CARGO_BUILD_TARGET=$X CUDA_OXIDE_LLC="$t/bin/llc21" bash "$oh"
  run 'a usage error ends 64' 64 'usage:' bash "$oh" --nonsense
  if [ "$fails" = 0 ]; then
    echo "oxide-host self-test: all green"
  else
    echo "oxide-host self-test: $fails red"
    return 1
  fi
}

cd "$ROOT"
case "${1-}" in
  '')
    triple=$(host_triple)
    write_config "$triple"
    check_llc
    check_backend
    ;;
  --flags)
    [ "$#" = 2 ] || { echo "usage: tools/oxide-host.sh [--flags TRIPLE | --llc | --backend | --self-test]" >&2; exit 64; }
    flags_of "$2"
    ;;
  --llc) check_llc ;;
  --backend) check_backend ;;
  --self-test) self_test ;;
  *)
    echo "usage: tools/oxide-host.sh [--flags TRIPLE | --llc | --backend | --self-test]" >&2
    exit 64
    ;;
esac
