#!/usr/bin/env bash
# The host CPU flags of an oxide build have one list per triple, in .cargo/config.toml (`[target.<triple>] rustflags`), and
# plain cargo reads it there. `cargo oxide` hides that table behind its own CARGO_ENCODED_RUSTFLAGS and reads one flat
# `extra-rustflags` list from .cargo/cuda-oxide.toml, the same for every triple (upstream issue NVIDIA/cuda-rust#1481), so
# tools/oxide-host.sh writes that file for the triple a build is for, from the config's list. This holds the pieces:
#   1. the config carries a list for the box's triple (znver3 with -sse4a) and for the Spark's (an aarch64 CPU name), with
#      no x86 name in the aarch64 list;
#   2. `tools/oxide-host.sh --flags <triple>` returns exactly the config's list for both, and refuses a triple that has
#      none (a build with no CPU flag would say nothing);
#   3. a .cargo/cuda-oxide.toml in the tree is the generated one (the old per-triple tables are ignored by cargo-oxide
#      without a word) and .gitignore keeps it out of the tree.
# It runs on the Mac (parsing and a bash script, no build).
#   tools/check-rustflags.sh [--self-test]
# Every run first runs its self-test quietly (the cases below: a missing list, an x86 name for aarch64, the old file shapes,
# a generator that drops a flag or falls back to a default are each red); --self-test prints the result line by line.
set -euo pipefail
cd "$(dirname "$0")/.."
python3 -I - "$@" <<'PY'
import os, shutil, subprocess, sys, tempfile, tomllib

X86 = "x86_64-unknown-linux-gnu"
ARM = "aarch64-unknown-linux-gnu"
NO_LIST = "mips-unknown-linux-gnu"  # a triple the config must never carry: the generator has to refuse it
HEADER = "# Generated by tools/oxide-host.sh"
OXIDE_FILE = ".cargo/cuda-oxide.toml"
# aarch64 CPU names the aarch64 list may hold; an x86 name there is a warning on every crate and a SIGSEGV inside LLVM on some.
ARM_CPUS = ("native", "generic")
ARM_CPU_PREFIXES = ("cortex-", "neoverse-", "apple-")


def codegen(flags):
    """The -C options of one rustflags list, `-C x`, `-Cx`, `--codegen x` and `--codegen=x` alike."""
    out, it = [], iter(flags or [])
    for f in it:
        if f in ("-C", "--codegen"):
            out.append(next(it, ""))
        elif f.startswith("--codegen="):
            out.append(f[len("--codegen="):])
        elif f.startswith("-C"):
            out.append(f[2:])
    # rustc takes `target_cpu` for `target-cpu`: the key is read with either separator.
    keyed = (o.partition("=") for o in out)
    return [key.replace("_", "-") + sep + value for key, sep, value in keyed]


def config_problems(cfg_text):
    """(the named failures of the config's lists, the lists by triple)."""
    cfg = tomllib.loads(cfg_text)
    tables = {t: v["rustflags"] for t, v in cfg.get("target", {}).items() if "rustflags" in v}
    bad = []
    for t in (X86, ARM):
        if not tables.get(t):
            bad.append(f"{t}: .cargo/config.toml has no [target.{t}] rustflags list — an oxide build for it would take no CPU flag")
    x86 = codegen(tables.get(X86))
    if tables.get(X86) and "target-cpu=znver3" not in x86:
        bad.append(f"{X86}: target-cpu=znver3 is not in the flags: {x86!r}")
    # znver3 turns on sse4a, and LLVM then lowers some byte shuffles to EXTRQ/INSERTQ, which have no VEX
    # form: inside AVX code each one takes a ymm spill fault, then fill faults, on Zen 3.
    if tables.get(X86) and "target-feature=-sse4a" not in x86:
        bad.append(f"{X86}: target-feature=-sse4a is not in the flags: {x86!r} — LLVM would emit "
                   "legacy-encoded EXTRQ/INSERTQ inside AVX kernels")
    # aarch64 takes only an aarch64 CPU name and no target-feature: an x86 name there is a warning on every
    # crate and a SIGSEGV inside LLVM on some, and no aarch64 feature is set today.
    arm = codegen(tables.get(ARM))
    foreign = [f for f in arm if f.startswith("target-feature=")
               or (f.startswith("target-cpu=")
                   and f[len("target-cpu="):] not in ARM_CPUS
                   and not f[len("target-cpu="):].startswith(ARM_CPU_PREFIXES))]
    if foreign:
        bad.append(f"{ARM}: CPU flags that are not an aarch64 CPU name: {foreign!r}")
    if NO_LIST in tables:
        bad.append(f"{NO_LIST}: the config carries a list for the triple the generator check uses as its refusal probe")
    return bad, tables


def generator(root, *args):
    r = subprocess.run(["bash", os.path.join(root, "tools/oxide-host.sh"), *args], capture_output=True, text=True, cwd=root)
    return r.returncode, r.stdout, r.stderr


def generator_problems(root, tables):
    """What tools/oxide-host.sh makes of the config: the same list per triple, and a refusal for a triple with none."""
    bad = []
    for t in (X86, ARM):
        if not tables.get(t):
            continue
        rc, out, err = generator(root, "--flags", t)
        if rc != 0:
            bad.append(f"{t}: tools/oxide-host.sh --flags ended {rc}: {err.strip()}")
        elif out.split("\n")[:-1] != list(tables[t]):
            bad.append(f"{t}: tools/oxide-host.sh --flags differs from the config's list — config {list(tables[t])!r}, generator {out.split(chr(10))[:-1]!r}")
    rc, out, err = generator(root, "--flags", NO_LIST)
    if rc != 70 or out:
        bad.append(f"{NO_LIST}: tools/oxide-host.sh does not refuse a triple with no list (rc {rc}, stdout {out!r}): "
                   "an oxide build for such a triple would take no CPU flag and say nothing")
    return bad


def file_problems(ox_text, ignore_text):
    bad = []
    if ox_text is not None and not ox_text.startswith(HEADER):
        bad.append(f"{OXIDE_FILE} is in the tree and was not generated by tools/oxide-host.sh: cargo-oxide ignores a "
                   "[target.<triple>] table in it without a word, and a flat extra-rustflags list reaches every triple")
    if f"/{OXIDE_FILE}" not in [ln.strip() for ln in ignore_text.splitlines()]:
        bad.append(f".gitignore does not list /{OXIDE_FILE}: the generated file would be committed")
    return bad


def check(root, cfg_text, ox_text, ignore_text):
    bad, tables = config_problems(cfg_text)
    return bad + generator_problems(root, tables) + file_problems(ox_text, ignore_text)


def scratch_tree(cfg_text, script_text):
    tmp = tempfile.mkdtemp(prefix="check-rustflags-")
    os.makedirs(os.path.join(tmp, ".cargo"))
    os.makedirs(os.path.join(tmp, "tools"))
    with open(os.path.join(tmp, ".cargo/config.toml"), "w", encoding="utf-8") as fh:
        fh.write(cfg_text)
    with open(os.path.join(tmp, "tools/oxide-host.sh"), "w", encoding="utf-8") as fh:
        fh.write(script_text)
    return tmp


def self_test(verbose):
    with open("tools/oxide-host.sh", encoding="utf-8") as fh:
        script = fh.read()
    good_cfg = (f'[target.{X86}]\nrustflags = ["-C", "target-cpu=znver3", "-C", "target-feature=-sse4a"]\n'
                f'[target.{ARM}]\nrustflags = ["-C", "target-cpu=native"]\n')
    generated = HEADER + " (untracked): ...\nextra-rustflags = []\n"
    ignore = "target/\n/.cargo/cuda-oxide.toml\n"
    lookup = 'flags = cfg.get("target", {}).get(triple, {}).get("rustflags")'
    emit = 'print("\\n".join(flags))'
    for anchor in (lookup, emit):
        if anchor not in script:
            print(f"check-rustflags self-test: BAD the mutation anchor {anchor!r} is not in tools/oxide-host.sh")
            return 1
    cases = [
        ("good", good_cfg, script, None, ignore, None),
        ("good with a generated file in the tree", good_cfg, script, generated, ignore, None),
        ("aarch64 list missing", good_cfg.split(f"[target.{ARM}]")[0], script, None, ignore, f"no [target.{ARM}] rustflags list"),
        ("x86_64 list missing", f'[target.{ARM}]\nrustflags = ["-C", "target-cpu=native"]\n', script, None, ignore, f"no [target.{X86}] rustflags list"),
        ("aarch64 list empty", good_cfg.replace('["-C", "target-cpu=native"]', "[]"), script, None, ignore, f"no [target.{ARM}] rustflags list"),
        ("aarch64 inherits znver3", good_cfg.replace("target-cpu=native", "target-cpu=znver3"), script, None, ignore, "not an aarch64 CPU name"),
        ("x86 lost sse4a", good_cfg.replace(', "-C", "target-feature=-sse4a"', ""), script, None, ignore, "target-feature=-sse4a is not in"),
        ("x86 lost znver3", good_cfg.replace("znver3", "x86-64-v3"), script, None, ignore, "target-cpu=znver3 is not in"),
        ("aarch64 haswell", good_cfg.replace("target-cpu=native", "target-cpu=haswell"), script, None, ignore, "not an aarch64 CPU name"),
        ("aarch64 x86 feature", good_cfg.replace('"target-cpu=native"', '"target-cpu=native", "-C", "target-feature=+bmi2"'),
         script, None, ignore, "not an aarch64 CPU name"),
        ("aarch64 target_cpu spelling", good_cfg.replace('"target-cpu=native"', '"target_cpu=znver3"'), script, None, ignore, "not an aarch64 CPU name"),
        ("the refusal probe's triple in the config", good_cfg + f'[target.{NO_LIST}]\nrustflags = ["-C", "target-cpu=generic"]\n',
         script, None, ignore, "the triple the generator check uses"),
        ("the old per-triple tables in the tree", good_cfg, script,
         f'[target.{X86}]\nextra-rustflags = ["-C", "target-cpu=znver3"]\n', ignore, "was not generated by tools/oxide-host.sh"),
        ("the old flat list in the tree", good_cfg, script, 'extra-rustflags = ["-C", "target-cpu=znver3"]\n', ignore, "was not generated by tools/oxide-host.sh"),
        ("the generated file is not ignored", good_cfg, script, None, "target/\n", "does not list /.cargo/cuda-oxide.toml"),
        ("a generator that drops the first flag", good_cfg, script.replace(emit, 'print("\\n".join(flags[1:]))'), None, ignore, "differs from the config's list"),
        ("a generator that falls back to a default list", good_cfg,
         script.replace(lookup, lookup + ' or ["-C", "target-cpu=x86-64"]'), None, ignore, "does not refuse a triple with no list"),
    ]
    failed = 0
    for name, cfg, scr, ox, ign, want in cases:
        tmp = scratch_tree(cfg, scr)
        try:
            bad = check(tmp, cfg, ox, ign)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
        ok = (not bad) if want is None else any(want in b for b in bad)
        if verbose or not ok:
            print(f"check-rustflags self-test: {'ok ' if ok else 'BAD'} {name}: {bad or 'clean'}")
        failed += not ok
    return failed


if sys.argv[1:] == ["--self-test"]:
    sys.exit(1 if self_test(True) else 0)
elif sys.argv[1:]:
    print(f"check-rustflags: usage: tools/check-rustflags.sh [--self-test], got {sys.argv[1:]!r}")
    sys.exit(64)
if self_test(False):
    print("check-rustflags: the self-test is red — the check itself is wrong")
    sys.exit(1)
for f in (".cargo/config.toml", ".gitignore", "tools/oxide-host.sh"):
    if not os.path.isfile(f):
        print(f"check-rustflags: {f} is missing")
        sys.exit(1)
with open(".cargo/config.toml", encoding="utf-8") as fh:
    cfg_text = fh.read()
ox_text = None
if os.path.isfile(OXIDE_FILE):
    with open(OXIDE_FILE, encoding="utf-8") as fh:
        ox_text = fh.read()
with open(".gitignore", encoding="utf-8") as fh:
    ignore_text = fh.read()
bad = check(os.getcwd(), cfg_text, ox_text, ignore_text)
for b in bad:
    print(f"check-rustflags: {b}")
if bad:
    sys.exit(1)
_, tables = config_problems(cfg_text)
for t in (X86, ARM):
    print(f"check-rustflags: ok — {t}: the config carries {tables[t]} and tools/oxide-host.sh returns the same list")
PY
